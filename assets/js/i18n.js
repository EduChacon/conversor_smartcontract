/* Utilitários de tradução compartilhados. */
(function () {
    'use strict';
    const CSC = window.CSC;
    CSC.lang = 'pt';
    CSC.t = function (key, vars) {
        const table = CSC.texts[CSC.lang] || CSC.texts.pt;
        let s = key in table ? table[key] : (CSC.texts.pt[key] !== undefined ? CSC.texts.pt[key] : key);
        if (typeof s === 'string' && vars) {
            s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
        }
        return s;
    };
})();
